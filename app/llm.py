"""LLM client interface with support for swappable OpenAI and Mock implementations."""

import json
import logging
import re
from abc import ABC, abstractmethod
from typing import Optional, Any, Dict, List
import httpx
from app.config import get_settings

logger = logging.getLogger(__name__)


def extract_json_payload(raw_text: str) -> Dict[str, Any]:
    """Extract and parse a JSON dictionary from raw model text.

    Handles markdown fences (```json ... ```), raw objects, and leading/trailing text.

    Args:
        raw_text: Raw string generated by the LLM.

    Returns:
        Parsed JSON dictionary.

    Raises:
        ValueError: If no valid JSON object could be extracted.
    """
    text = raw_text.strip()

    # Pattern 1: Check for markdown code blocks ```json ... ```
    match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
    if match:
        text = match.group(1).strip()
    else:
        # Pattern 2: Search for outermost curly braces
        match = re.search(r"(\{.*\})", text, re.DOTALL)
        if match:
            text = match.group(1).strip()

    # Clean common LLM formatting artifacts
    text = re.sub(r",\s*([\}\]])", r"\1", text)

    try:
        data = json.loads(text)
        if isinstance(data, dict):
            return data
        raise ValueError("Parsed JSON is not a dictionary.")
    except Exception as exc:
        raise ValueError(f"Failed to parse JSON from output: {raw_text[:200]}") from exc


class BaseLLMClient(ABC):
    """Abstract interface for LLM text and structured JSON generation."""

    @abstractmethod
    def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        temperature: float = 0.0,
    ) -> str:
        """Generate raw text response from the model."""
        pass

    def generate_json(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        max_retries: int = 2,
    ) -> Dict[str, Any]:
        """Generate response and parse it as JSON with retry handling.

        Args:
            prompt: User prompt containing instructions and input data.
            system_prompt: Optional system prompt specifying JSON output format.
            max_retries: Number of retry attempts if invalid JSON is returned.

        Returns:
            Extracted JSON dictionary.

        Raises:
            ValueError: If valid JSON cannot be generated after retries.
        """
        current_prompt = prompt
        last_error = None

        for attempt in range(max_retries + 1):
            raw_output = self.generate(
                prompt=current_prompt,
                system_prompt=system_prompt,
            )
            try:
                return extract_json_payload(raw_output)
            except ValueError as err:
                last_error = err
                logger.warning(
                    "JSON parsing failed on attempt %d/%d: %s. Retrying...",
                    attempt + 1,
                    max_retries + 1,
                    str(err),
                )
                current_prompt = (
                    f"{prompt}\n\nIMPORTANT: Your previous output was invalid JSON. "
                    f"Return ONLY valid JSON with no markdown and no surrounding text.\n"
                    f"Previous error: {str(err)}"
                )

        raise ValueError(f"LLM failed to return valid JSON after {max_retries + 1} attempts: {last_error}")


class MockLLMClient(BaseLLMClient):
    """Deterministic Mock LLM client for offline execution and testing.

    Can be programmed with explicit responses or use rule-based heuristics
    tailored to IT support triage scenarios.
    """

    def __init__(self, predefined_responses: Optional[List[str]] = None):
        self.predefined_responses: List[str] = predefined_responses or []
        self.call_history: List[Dict[str, Any]] = []

    def set_responses(self, responses: List[str]) -> None:
        """Inject a list of mock responses to be popped in sequence."""
        self.predefined_responses = list(responses)

    def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        temperature: float = 0.0,
    ) -> str:
        """Return a queued predefined response or generate a heuristic response."""
        self.call_history.append({
            "prompt": prompt,
            "system_prompt": system_prompt,
            "temperature": temperature,
        })

        if self.predefined_responses:
            return self.predefined_responses.pop(0)

        # Heuristic simulation based on agent prompts
        lower_prompt = (prompt + " " + (system_prompt or "")).lower()

        # 1. Reviewer Agent Prompt
        if "reviewer agent" in lower_prompt or "review the drafted resolution" in lower_prompt:
            # Check for policy violations
            if any(term in lower_prompt for term in ["enter your password", "send me your password", "provide your password", "reveal your password", "give your password"]):
                return json.dumps({
                    "decision": "needs_human_approval",
                    "confidence": 0.95,
                    "policy_violations": ["CRITICAL: Resolution requests or handles sensitive user password"],
                    "missing_information": [],
                    "reasoning": "Draft resolution violates enterprise security policy by requesting credentials.",
                    "suggested_edits": "Remove any request for user passwords and redirect to the self-service SSPR portal.",
                })

            if "critical" in lower_prompt:
                return json.dumps({
                    "decision": "needs_human_approval",
                    "confidence": 0.90,
                    "policy_violations": [],
                    "missing_information": [],
                    "reasoning": "Critical priority ticket requires mandatory human supervisor authorization.",
                    "suggested_edits": None,
                })

            if "low confidence" in lower_prompt or "confidence: 0.5" in lower_prompt or "confidence: 0.6" in lower_prompt:
                return json.dumps({
                    "decision": "needs_human_approval",
                    "confidence": 0.60,
                    "policy_violations": [],
                    "missing_information": ["Missing network gateway log details"],
                    "reasoning": "Resolution confidence is below threshold.",
                    "suggested_edits": "Verify specific IP address and firewall rule before replying.",
                })

            return json.dumps({
                "decision": "auto_send",
                "confidence": 0.92,
                "policy_violations": [],
                "missing_information": [],
                "reasoning": "Resolution is accurate, adheres to IT security guidelines, and does not request passwords.",
                "suggested_edits": None,
            })

        # 2. Classifier Agent Prompt
        if "classifier agent" in lower_prompt or "classify the following support ticket" in lower_prompt:
            # Check for critical keywords
            is_critical = any(kw in lower_prompt for kw in ["outage", "production down", "urgent", "ransomware", "breach", "phishing"])
            priority = "critical" if is_critical else ("high" if "vpn" in lower_prompt or "locked out" in lower_prompt else "medium")

            category = "other"
            if any(kw in lower_prompt for kw in ["vpn", "wifi", "corpnet", "dns", "network", "internet", "connection"]):
                category = "network"
            elif any(kw in lower_prompt for kw in ["password", "lockout", "mfa", "login", "access", "sso", "authenticator", "okta"]):
                category = "access"
            elif any(kw in lower_prompt for kw in ["laptop", "battery", "monitor", "dock", "screen", "printer", "keyboard", "hardware"]):
                category = "hardware"
            elif any(kw in lower_prompt for kw in ["outlook", "slack", "zoom", "software", "install", "app", "license", "ost"]):
                category = "software"

            confidence = 0.90
            if "ambiguous" in lower_prompt or "vague" in lower_prompt:
                confidence = 0.55

            return json.dumps({
                "category": category,
                "priority": priority,
                "confidence": confidence,
                "reasoning": f"Ticket classified as {category} with {priority} priority based on customer issue description.",
            })

        # 3. Resolver Agent Prompt
        if "resolver agent" in lower_prompt or "draft an it resolution" in lower_prompt:
            return json.dumps({
                "draft_resolution": (
                    "Hello,\n\nThank you for reaching out to IT Support. Based on your description, "
                    "please follow these steps to resolve the issue:\n"
                    "1. Disconnect and re-open the application.\n"
                    "2. Navigate to Settings and refresh your connection/credentials via our SSO portal.\n"
                    "3. If the issue persists, reboot your system.\n\n"
                    "Please let us know if you need further assistance.\n\nBest regards,\nIT Service Desk"
                ),
                "confidence": 0.88,
                "reasoning": "Matched standard operating procedures and verified knowledge base guidance.",
                "sources_used": ["vpn_troubleshooting.md"],
            })

        # Generic JSON fallback
        return json.dumps({"status": "ok", "message": "Mock generic response"})


class OpenAILLMClient(BaseLLMClient):
    """OpenAI / OpenAI-compatible API client."""

    def __init__(
        self,
        api_key: str,
        model: str = "gpt-4o-mini",
        base_url: str = "https://api.openai.com/v1",
    ):
        self.api_key = api_key
        self.model = model
        self.base_url = base_url.rstrip("/")

    def generate(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        temperature: float = 0.0,
    ) -> str:
        """Call chat completion endpoint."""
        messages = []
        if system_prompt:
            messages.append({"role": "system", "content": system_prompt})
        messages.append({"role": "user", "content": prompt})

        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self.model,
            "messages": messages,
            "temperature": temperature,
        }

        with httpx.Client(timeout=60.0) as client:
            resp = client.post(
                f"{self.base_url}/chat/completions",
                headers=headers,
                json=payload,
            )
            resp.raise_for_status()
            data = resp.json()
            return data["choices"][0]["message"]["content"]


_llm_client_instance: Optional[BaseLLMClient] = None


def get_llm_client() -> BaseLLMClient:
    """Provide configured singleton LLM client based on environment settings."""
    global _llm_client_instance
    if _llm_client_instance is not None:
        return _llm_client_instance

    settings = get_settings()

    if settings.llm_provider.lower() == "openai" and settings.llm_api_key:
        logger.info("Initializing OpenAILLMClient with model: %s", settings.llm_model)
        _llm_client_instance = OpenAILLMClient(
            api_key=settings.llm_api_key,
            model=settings.llm_model,
            base_url=settings.llm_base_url,
        )
    else:
        logger.info("Initializing MockLLMClient for offline execution.")
        _llm_client_instance = MockLLMClient()

    return _llm_client_instance


def set_llm_client(client: BaseLLMClient) -> None:
    """Override singleton client instance (useful for unit tests)."""
    global _llm_client_instance
    _llm_client_instance = client
