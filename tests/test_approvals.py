"""Tests for human-in-the-loop approval and rejection workflows."""

from app.models import Ticket, Approval, AgentLog


def test_approve_ticket_endpoint(client, db_session):
    """Test standard approval of a pending ticket."""
    ticket = Ticket(
        customer_name="Alice Morgan",
        customer_email="alice@example.com",
        subject="Request for specialized tool",
        description="Need compiler toolchain installed.",
        status="pending_approval",
        category="software",
        priority="medium",
        draft_resolution="Approved tool installation via Company Portal.",
    )
    db_session.add(ticket)
    db_session.commit()

    approval = Approval(
        ticket_id=ticket.id,
        status="pending",
        reviewer_notes="Low confidence draft needs confirmation.",
    )
    db_session.add(approval)
    db_session.commit()

    response = client.post(
        f"/tickets/{ticket.id}/approve",
        json={"reviewer_notes": "Supervisor verified user license eligibility."},
    )
    assert response.status_code == 200
    data = response.json()

    assert data["status"] == "resolved"
    assert data["final_resolution"] == "Approved tool installation via Company Portal."

    # Verify approval record updated in DB
    db_approval = db_session.query(Approval).filter(Approval.ticket_id == ticket.id).first()
    assert db_approval.status == "approved"
    assert "license eligibility" in db_approval.reviewer_notes
    assert db_approval.decided_at is not None

    # Verify audit log recorded human supervisor action
    supervisor_log = (
        db_session.query(AgentLog)
        .filter(AgentLog.ticket_id == ticket.id, AgentLog.agent_name == "human_supervisor")
        .first()
    )
    assert supervisor_log is not None


def test_approve_ticket_with_edited_resolution(client, db_session):
    """Test approval with human supervisor editing the final resolution."""
    ticket = Ticket(
        customer_name="Bob Vance",
        customer_email="bob@example.com",
        subject="Password reset issue",
        description="Need urgent reset.",
        status="pending_approval",
        draft_resolution="Draft resolution generated by agent.",
    )
    db_session.add(ticket)
    db_session.commit()

    edited_text = "Custom human-crafted resolution directing user to SSPR with priority phone PIN."
    response = client.post(
        f"/tickets/{ticket.id}/approve",
        json={
            "edited_response": edited_text,
            "reviewer_notes": "Added custom security instructions.",
        },
    )
    assert response.status_code == 200
    data = response.json()

    assert data["status"] == "resolved"
    assert data["final_resolution"] == edited_text


def test_reject_ticket_endpoint(client, db_session):
    """Test rejection of a pending ticket draft."""
    ticket = Ticket(
        customer_name="Charlie Brown",
        customer_email="charlie@example.com",
        subject="Non-business personal software request",
        description="Please install Steam on my work laptop.",
        status="pending_approval",
        draft_resolution="Installing gaming software.",
    )
    db_session.add(ticket)
    db_session.commit()

    response = client.post(
        f"/tickets/{ticket.id}/reject",
        json={"reviewer_notes": "Denied: Personal gaming software is unauthorized under AUP."},
    )
    assert response.status_code == 200
    data = response.json()

    assert data["status"] == "rejected"
    assert data["final_resolution"] is None

    db_approval = db_session.query(Approval).filter(Approval.ticket_id == ticket.id).first()
    assert db_approval.status == "rejected"
    assert "AUP" in db_approval.reviewer_notes


def test_approve_non_pending_ticket_returns_400(client, db_session):
    """Test that attempting to approve a non-pending ticket yields 400 Bad Request."""
    ticket = Ticket(
        customer_name="David",
        customer_email="david@example.com",
        subject="Already resolved issue",
        description="All done.",
        status="resolved",
    )
    db_session.add(ticket)
    db_session.commit()

    response = client.post(f"/tickets/{ticket.id}/approve", json={})
    assert response.status_code == 400
    assert "not awaiting approval" in response.json()["detail"].lower()
